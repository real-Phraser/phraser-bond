/**
 * Initializes 3D Tilt perspective and cursor spotlight on an element
 * @param {HTMLElement|string} target
 */
export function initCardTilt(target = '.container') {
  const cards = typeof target === 'string' ? document.querySelectorAll(target) : [target];
  if (!cards.length) return;

  cards.forEach((card) => {
    if (!card) return;

    const handleMouseMove = (e) => {
      const rect = card.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;

      card.style.setProperty('--mouse-x', `${x}px`);
      card.style.setProperty('--mouse-y', `${y}px`);

      const centerX = rect.width / 2;
      const centerY = rect.height / 2;
      const rotateX = -((y - centerY) / centerY) * 6;
      const rotateY = ((x - centerX) / centerX) * 6;

      card.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-4px)`;
    };

    const handleMouseLeave = () => {
      card.style.transform = `perspective(1000px) rotateX(0deg) rotateY(0deg) translateY(0px)`;
    };

    window.addEventListener('mousemove', (e) => {
      // If hovering near the card
      const rect = card.getBoundingClientRect();
      if (
        e.clientX >= rect.left - 50 &&
        e.clientX <= rect.right + 50 &&
        e.clientY >= rect.top - 50 &&
        e.clientY <= rect.bottom + 50
      ) {
        handleMouseMove(e);
      }
    });

    card.addEventListener('mouseleave', handleMouseLeave);
  });
}

/**
 * Animated dots runner (e.g. "coming soon...")
 * @param {HTMLElement|string} target
 * @param {number} interval
 */
export function initDotsAnimation(target = '#dots', interval = 500) {
  const el = typeof target === 'string' ? document.querySelector(target) : target;
  if (!el) return null;

  let step = 0;
  return setInterval(() => {
    step = (step + 1) % 4;
    el.textContent = '.'.repeat(step);
  }, interval);
}

